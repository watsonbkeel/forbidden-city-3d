"""Rebuild only the caisson increment from the preserved pre-caisson asset.

Run from any directory. Outputs the content-addressed GLB, local fallback data,
and a finite provenance manifest; does not edit source registry automatically.
"""
import base64
import json
from pathlib import Path
import struct
import sys

from append_taihe_caisson import append_batches, sha
from retire_taihe_shell import retire_shell
from taihe_caisson.shell import build_shell
from taihe_caisson.geometry import build_candidate, material_batches

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BASE = ROOT / 'public/models/interiors/taihe-v17-display-28d7a11dbeda.glb'
BASE_SHA = '28d7a11dbeda023762c8c9eed44eb65c5f4c8270ddfb9d7088e40f6b6991399c'


def inventory(mesh, prefix="caisson_dragon_"):
    rows = []
    for name, faces in mesh['parts'].items():
        points = [mesh['vertices'][j] for i in faces for j in mesh['triangles'][i]]
        rows.append({'name': prefix + name,
                     'min': [min(p[k] for p in points) for k in range(3)],
                     'max': [max(p[k] for p in points) for k in range(3)]})
    return rows


def render_fallback(batches, source_sha):
    rows = []
    for key, batch in batches.items():
        row = {'material': key}
        for name in ['position', 'normal']:
            values = batch[name]
            row[name] = base64.b64encode(struct.pack('<' + 'f' * len(values), *values)).decode()
        rows.append(row)
    return ('// Generated by assets-src/interiors/build_taihe_caisson.py.\n'
            '// Estimated caisson shell and central dragon silhouette; no imagery or runtime fetch.\n'
            '// Geometry source SHA256: ' + source_sha + '\n'
            'export const TAIHE_CAISSON_FALLBACK_DATA = ' + json.dumps(rows, separators=(',', ':')) + ';\n')


def build(output=None):
    output = Path(output) if output else ROOT
    profile = json.loads((ROOT / 'data/architecture/taihe-core.json').read_bytes())
    base = BASE.read_bytes()
    if sha(base) != BASE_SHA:
        raise ValueError('Frozen pre-caisson GLB changed')
    mask_path = HERE / 'taihe_caisson/retired_shell_faces.json'
    retired_base, retirement = retire_shell(base, mask_path.read_bytes())
    meshes = {quality: build_candidate(profile['caisson'], quality) for quality in ['detail', 'fallback']}
    shells = {quality: build_shell(profile['caisson'], quality) for quality in ['detail', 'fallback']}
    batches = {}
    for quality in ['detail', 'fallback']:
        batches[quality] = {}
        for source in [shells[quality], meshes[quality]]:
            for key, batch in material_batches(source).items():
                target = batches[quality].setdefault(key, {'position': [], 'normal': [], 'indices': []})
                offset = len(target['position']) // 3
                target['position'].extend(batch['position']); target['normal'].extend(batch['normal'])
                target['indices'].extend(i + offset for i in batch['indices'])
    source_sha = sha((HERE / 'taihe_caisson/geometry.py').read_bytes())
    identity = {'caissonSourceSHA256': source_sha,
                'caissonIntegrationSHA256': sha((HERE / 'append_taihe_caisson.py').read_bytes()),
                'caissonBaseAssetSHA256': BASE_SHA,
                'caissonTriangles': len(meshes['detail']['triangles']),
                'caissonShellSourceSHA256': sha((HERE / 'taihe_caisson/shell.py').read_bytes()),
                'caissonShellRetirementSHA256': sha((HERE / 'retire_taihe_shell.py').read_bytes()),
                'caissonShellMaskSHA256': sha(mask_path.read_bytes()),
                'caissonShellTriangles': len(shells['detail']['triangles']),
                'caissonRemovedTriangles': retirement['removedTriangles']}
    added_inventory = inventory(shells['detail'], 'caisson_shell_') + inventory(meshes['detail'])
    glb, prefixes = append_batches(retired_base, batches['detail'], identity, added_inventory)
    digest = sha(glb)
    relative = 'public/models/interiors/taihe-caisson-' + digest[:12] + '.glb'
    fallback = render_fallback(batches['fallback'], source_sha).encode()
    fallback_path = 'src/scene/palace/special/TaiheCaissonFallbackData.js'
    for path, data in [(relative, glb), (fallback_path, fallback)]:
        target = output / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    manifest = {'schema': 'taihe-caisson-shell-replacement-2', 'status': 'source-informed estimated visual candidate; pixel review pending',
                'baselineAsset': str(BASE.relative_to(ROOT)), 'baselineSHA256': BASE_SHA,
                'sources': {str(p.relative_to(ROOT)): sha(p.read_bytes()) for p in [
                    HERE / 'taihe_caisson/geometry.py', HERE / 'taihe_caisson/shell.py', mask_path,
                    HERE / 'retire_taihe_shell.py', HERE / 'append_taihe_caisson.py', Path(__file__)]},
                'profileSHA256': sha((ROOT / 'data/architecture/taihe-core.json').read_bytes()),
                'asset': {'path': relative, 'sha256': digest, 'encodedBytes': len(glb),
                          'renderableTriangles': 12128 - retirement['removedTriangles'] + identity['caissonTriangles'] + identity['caissonShellTriangles'], 'visibleBatches': 8},
                'identity': identity, 'accessorPrefixes': prefixes, 'retirement': retirement, 'appendedInventory': added_inventory,
                'fallback': {'path': fallback_path, 'sha256': sha(fallback), 'encodedBytes': len(fallback),
                             'addedTriangles': len(meshes['fallback']['triangles']) + len(shells['fallback']['triangles']),
                             'dragonTriangles': len(meshes['fallback']['triangles']),
                             'shellTriangles': len(shells['fallback']['triangles']), 'retiredTriangles': 48,
                             'renderableTriangles': 1558 - 48 + len(meshes['fallback']['triangles']) + len(shells['fallback']['triangles']), 'visibleBatches': 8},
                'geometry': {q: {'triangles': len(m['triangles']), 'metadata': m['metadata'], 'inventory': inventory(m)} for q,m in meshes.items()},
                'shell': {q: {'triangles': len(m['triangles']), 'inventory': inventory(m, 'caisson_shell_')} for q,m in shells.items()},
                'unchanged': ['opening and caisson anchor', 'all seven pearls', 'dais and screen placement', 'navigation', 'material properties', 'lighting', '8-batch and original scene performance budgets']}
    target = output / 'docs/current-state/taihe-caisson/SOURCE-MANIFEST.json'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    return manifest


if __name__ == '__main__':
    result = build(sys.argv[1] if len(sys.argv) > 1 else None)
    print(json.dumps({'asset': result['asset'], 'fallback': result['fallback']}, ensure_ascii=False))
