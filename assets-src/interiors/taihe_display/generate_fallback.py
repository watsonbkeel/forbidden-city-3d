"""Generate compact local fallback data from the frozen approved mesh source.
No browser, runtime fetch, material creation, or source geometry mutation.
Run from anywhere: python assets-src/interiors/taihe_display/generate_fallback.py
"""
import base64
import hashlib
import json
from pathlib import Path
import struct
import sys
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / 'approved'))
from taihe_display_pairs import build_display_pairs, MATERIAL_KEYS
from integration_geometry import flat_attributes
ROOT = HERE.parents[2]
DEFAULT = ROOT / 'src/scene/palace/special/TaiheDisplayFallbackData.js'


def render():
    batches = {key: {'position': [], 'normal': []} for key in MATERIAL_KEYS}
    for item in build_display_pairs('fallback'):
        for key, batch in batches.items():
            attrs = flat_attributes(item['local_mesh'], key)
            batch['position'].extend(v + item['translation'][i % 3] for i, v in enumerate(attrs['position']))
            batch['normal'].extend(attrs['normal'])
    packed = []
    for key, attrs in batches.items():
        if not attrs['position']:
            continue
        record = {'material': key}
        for name, values in attrs.items():
            record[name] = base64.b64encode(struct.pack('<' + 'f' * len(values), *values)).decode('ascii')
        packed.append(record)
    assert sum(len(b['position']) // 9 for b in batches.values()) == 480
    digest = hashlib.sha256((HERE / 'approved/artifacts/SOURCE-MANIFEST.json').read_bytes()).hexdigest()
    return ('// Generated by assets-src/interiors/taihe_display/generate_fallback.py. Do not hand-edit.\n'
            '// Frozen R2 source SHA256: ' + digest + '\n'
            '// 480 triangles; flat per-face attributes; explicit reverse sheets are counted.\n'
            '// Self-authored approximate shapes/placement; no imagery, fonts or runtime fetch.\n'
            'export const TAIHE_DISPLAY_FALLBACK_DATA = ' + json.dumps(packed, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    out.write_text(render())
    print(json.dumps({'path': str(out), 'bytes': out.stat().st_size,
                      'sha256': hashlib.sha256(out.read_bytes()).hexdigest()}))
