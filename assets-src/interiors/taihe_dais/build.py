"""Exact retirement + append. Keeps all unrelated bytes and original eight batches.
The old asset is retained. A pinned source-semantic mask is verified per face.
"""
import sys,json,struct,copy,base64,collections
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3];sys.path.insert(0,str(ROOT/'assets-src/interiors'))
from append_taihe_caisson import unpack_glb,pack_glb,sha
from append_taihe_screen import append_batches as append_arch
from append_taihe_cranes import append_batches as append_teal
from geometry import build
from integration_geometry import flat_attributes
BASE=ROOT/'public/models/interiors/taihe-furnishing-surfaces-a4a0b82f9f76.glb'
BASE_SHA='a4a0b82f9f767422db824b9c0f9039fc3da2234f18b3d584d295ad52020ec529'
MASK=Path(__file__).with_name('retirement-mask.json');MASK_SHA='22e89735e7f1277e901cd2c894ad0e1e9763c26c83e1753e406a8d6287527795'
def retire(base):
 if sha(base)!=BASE_SHA or sha(MASK.read_bytes())!=MASK_SHA:raise ValueError('Changed frozen dais input')
 mask=json.loads(MASK.read_text());g,b=unpack_glb(base);g=copy.deepcopy(g)
 chunks=[b[v['byteOffset']:v['byteOffset']+v['byteLength']] for v in g['bufferViews']];receipts=[]
 for material,info in mask['materials'].items():
  p=g['meshes'][info['mesh']]['primitives'][0];assert g['materials'][p['material']]['name']==material
  a=g['accessors'][p['indices']];fmt={5123:'H',5125:'I'}[a['componentType']];vi=a['bufferView'];before=chunks[vi];ids=struct.unpack('<'+fmt*a['count'],before)
  assert len(ids)//3==info['originalTriangles'] and not a.get('byteOffset')
  pos=chunks[g['accessors'][p['attributes']['POSITION']]['bufferView']];rows=[r for r in mask['triangles'] if r['material']==material];removed=set()
  for r in rows:
   j=r['triangleOrdinal'];ix=ids[j*3:j*3+3]
   if list(ix)!=r['indices'] or sha(b''.join(pos[i*12:i*12+12] for i in ix))!=r['positionSHA256'] or j in removed:raise ValueError('Changed exact retirement face')
   removed.add(j)
  assert len(rows)==mask['counts'][material]
  kept=[v for j in range(0,len(ids),3) if j//3 not in removed for v in ids[j:j+3]];chunks[vi]=struct.pack('<'+fmt*len(kept),*kept);a['count']=len(kept)
  if 'min' in a:a['min']=[min(kept)]
  if 'max' in a:a['max']=[max(kept)]
  receipts.append({'material':material,'removedTriangles':len(removed),'beforeIndexSHA256':sha(before),'retainedIndexSHA256':sha(chunks[vi])})
 c=next(n['extras'] for n in g['nodes'] if n.get('name')=='TAIHE_CORE_CONTRACT');inventory=json.loads(c['inventory'])
 whole={p for p in mask['parts'] if not p.startswith('gold_column')};c['inventory']=json.dumps([r for r in inventory if r['name'] not in whole],separators=(',',':'))
 packed=bytearray()
 for v,ch in zip(g['bufferViews'],chunks):packed+=b'\0'*(-len(packed)%4);v['byteOffset']=len(packed);v['byteLength']=len(ch);packed+=ch
 g['buffers'][0]['byteLength']=len(packed)
 return pack_glb(g,packed),receipts

def main(output=None):
 output=Path(output) if output else ROOT
 geom=build('S');data=geom.data();batches={};inventory=[]
 for material in sorted(set(geom.materials)):
  a=flat_attributes(data,material);batches[material]={'position':a['position'],'normal':a['normal'],'indices':list(range(len(a['position'])//3))}
 for name in sorted(set(geom.components)):
  verts=[geom.vertices[v] for i,t in enumerate(geom.triangles) if geom.components[i]==name for v in t]
  inventory.append({'name':'r7_dais_'+name,'min':[min(v[k] for v in verts) for k in range(3)],'max':[max(v[k] for v in verts) for k in range(3)]})
 retired,receipt=retire(BASE.read_bytes())
 source=Path(__file__).with_name('geometry.py')
 identity={'daisFrontBaseSHA256':BASE_SHA,'daisFrontMaskSHA256':MASK_SHA,'daisFrontGeometrySHA256':sha(source.read_bytes()),'daisFrontProfileSHA256':sha((ROOT/'data/architecture/taihe-dais-front.json').read_bytes()),'daisFrontAddedTriangles':len(geom.triangles),'daisFrontRemovedTriangles':744}
 first,arch=append_arch(retired,{k:v for k,v in batches.items() if k!='teal'},identity,inventory)
 result,teal=append_teal(first,{'teal':batches['teal']},{'daisFrontTealIntegrated':True},[])
 digest=sha(result);relative=f'public/models/interiors/taihe-dais-front-{digest[:12]}.glb';(output/relative).parent.mkdir(parents=True,exist_ok=True);(output/relative).write_bytes(result)
 fallback=build('B').data();rows=[]
 for key in sorted(set(fallback['materials'])):
  a=flat_attributes(fallback,key);rows.append({'material':key,**{n:base64.b64encode(struct.pack('<'+'f'*len(a[n]),*a[n])).decode() for n in ['position','normal']}})
 fallbackPath=output/'src/scene/palace/special/TaiheDaisFallbackData.js';fallbackPath.parent.mkdir(parents=True,exist_ok=True);fallbackPath.write_text('// Generated by assets-src/interiors/taihe_dais/build.py; estimated shapes, not surveyed.\nexport const TAIHE_DAIS_FALLBACK_DATA='+json.dumps(rows,separators=(',',':'))+';\n')
 manifest={'schema':'taihe-dais-front-1','status':'source-informed candidate; actual scene review pending','asset':{'path':relative,'sha256':digest,'encodedBytes':len(result),'visibleTriangles':17940-744+len(geom.triangles),'batches':8},'baselineSHA256':BASE_SHA,'retirement':receipt,'append':arch+teal,'identity':identity,'fallback':{'sha256':sha(fallbackPath.read_bytes()),'addedTriangles':len(fallback['triangles'])},'sources':{str(p.relative_to(ROOT)):sha(p.read_bytes()) for p in [source,Path(__file__),MASK,ROOT/'data/architecture/taihe-dais-front.json']}}
 manifestPath=output/'docs/current-state/taihe-dais-front/SOURCE-MANIFEST.json';manifestPath.parent.mkdir(parents=True,exist_ok=True);manifestPath.write_text(json.dumps(manifest,indent=2)+'\n')
 print(json.dumps({'asset':manifest['asset'],'added':len(geom.triangles),'fallbackAdded':len(fallback['triangles'])}))
if __name__=='__main__':main(sys.argv[1] if len(sys.argv)>1 else None)
