// Deterministic technical sampling of unmodified generated artwork, not a depth
// reconstruction. Uses the project's already-installed PNG codec; no browser.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url),root=path.dirname(require.resolve('playwright-core/package.json'));
const {PNG}=require(root+'/lib/utilsBundle.js');
const here=path.dirname(fileURLToPath(import.meta.url));
const input=fs.readFileSync(path.join(here,'original-generated.png')),image=PNG.sync.read(input);
const width=224,height=480,band=12,data=new Uint8Array(width*height),raw=new Float64Array(width*height);
if(image.width!==890||image.height!==1768)throw new Error('Unexpected authored artwork dimensions');
// Exact area-box prefilter in image/luminance space before 8-bit quantization.
// This artistic luminance remains encoded brightness, not recovered geometry.
for(let y=0;y<height;y++)for(let x=0;x<width;x++){
 const x0=x*image.width/width,x1=(x+1)*image.width/width,y0=(height-1-y)*image.height/height,y1=(height-y)*image.height/height;
 let total=0,area=0;
 for(let sy=Math.floor(y0);sy<Math.ceil(y1);sy++)for(let sx=Math.floor(x0);sx<Math.ceil(x1);sx++){
  const a=(Math.min(x1,sx+1)-Math.max(x0,sx))*(Math.min(y1,sy+1)-Math.max(y0,sy)),i=(sy*image.width+sx)*4;
  total+=a*(image.data[i]*.2126+image.data[i+1]*.7152+image.data[i+2]*.0722);area+=a;
 }raw[y*width+x]=total/area;
}
for(let y=0;y<height;y++){
 const offset=y*width,common=(raw[offset]+raw[offset+1]+raw[offset+width-2]+raw[offset+width-1])/4;
 for(let x=0;x<width;x++){
  const edge=Math.min(x,width-1-x),t=Math.max(0,Math.min(1,(edge-1)/(band-2))),smooth=t*t*(3-2*t);
  // Two equal texels at each edge give an exact flat derivative at the join;
  // cubic transition returns to the unmodified prefiltered sample at texel 11.
  data[offset+x]=Math.round(edge<band?common*(1-smooth)+raw[offset+x]*smooth:raw[offset+x]);
 }
}
const sha=b=>createHash('sha256').update(b).digest('hex');
const source=`// Generated by assets-src/interiors/taihe_column_art/bake.mjs. Do not edit.\n// AI-generated decorative artwork; scalar brightness is NOT measured depth.\nexport const COLUMN_INTENSITY_WIDTH=${width};\nexport const COLUMN_INTENSITY_HEIGHT=${height};\nexport const COLUMN_INTENSITY_SHA256='${sha(data)}';\nexport const COLUMN_INTENSITY_BASE64='${Buffer.from(data).toString('base64')}';\n`;
const destination=process.argv[2]??path.resolve(here,'../../../src/scene/palace/special/TaiheColumnIntensityData.js');
fs.writeFileSync(destination,source);
console.log(JSON.stringify({inputSHA256:sha(input),inputBytes:input.length,inputSize:[image.width,image.height],outputSize:[width,height],outputBytes:data.length,outputSHA256:sha(data),moduleBytes:Buffer.byteLength(source),moduleSHA256:sha(source),edgeBand:band,orientation:'bottom-up for flipY=false DataTexture',filter:'area-box average of encoded grayscale luminance, then symmetric cubic periodicization, then uint8 rounding'},null,2));
