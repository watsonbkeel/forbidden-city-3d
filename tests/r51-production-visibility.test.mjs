import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {tmpdir} from 'node:os';
import {exportProductionView} from './lib/r51-production-raster.mjs';
import {compileProductionMain,lightWorld,installMainEnvironment,submittedInstances,advanceMain} from './lib/r51-production-main.mjs';

const reportDirectory=path.resolve('reports/r51');fs.mkdirSync(reportDirectory,{recursive:true});
const frozenDirectory=process.env.R51_VISIBILITY_BASE_DIR||null;
const geometryDirectory=process.env.R51_VISIBILITY_GEOMETRY_DIR||path.join(tmpdir(),'r51-production-visibility-geometry');
fs.mkdirSync(geometryDirectory,{recursive:true});
const fullWorld=process.env.R51_VISIBILITY_FULL_WORLD==='1';
const suffix=process.env.R51_VISIBILITY_REPORT_SUFFIX??(!frozenDirectory&&fs.existsSync(path.join(reportDirectory,'production-visibility-green-fullworld-after-lod2.json'))?'-after-lod2':'');
const label=(frozenDirectory?'red-base':fullWorld?'green-fullworld':'green')+suffix;
const compiled=await compileProductionMain({frozenDirectory});
const report={createdAt:new Date().toISOString(),label,proofBoundary:'CPU production compilation and complete main entry wiring, not browser/WebGL frame, texture appearance, historical acceptance, or full-world certification.',entry:compiled.evidence,checks:[]};

await test('production main boots ordinary characters into real InstancedMesh batches without preview or approval',async t=>{
 const W=fullWorld ? await (await import('./p3c-world-fixture.mjs')).buildCharacterWorld() : lightWorld();
 report.world={kind:fullWorld?'Fresh production buildCharacterWorld: all-zone colliders, actual static architecture and west-six render geometry':W.kind,colliders:W.cm.colliders.length,walkables:W.cm.walkables.length};
 const host=installMainEnvironment(W),app=new compiled.module.ForbiddenCityApp();
 t.after(()=>{app.dispose();host.restore();fs.writeFileSync(path.join(reportDirectory,`production-visibility-${label}.json`),JSON.stringify(report,null,2)+'\n');});
 await app.init();
 const first=app.characters.snapshot(),button=app.settingsMenu.panel.querySelector('#characters-toggle-btn');
 report.initial={snapshot:first,settings:{enabled:app.settingsMenu.charactersEnabled,button:button.textContent,pressed:button.getAttribute('aria-pressed')},render:submittedInstances(app)};
 assert.equal(app.characters.renderer.scene,app.scene,'real CharacterRenderer owns main scene');
 assert.equal(app.characters.world.scene,app.scene,'real WorldAdapter reads main scene');
 assert.equal(app.characters.camera,app.camera,'characters use the actual main camera');
 assert.equal(app.settingsMenu.charactersEnabled,app.characters.enabled,'initial Settings state must match actual System');
 assert.equal(button.getAttribute('aria-pressed'),String(app.characters.enabled));
 assert.equal(app.settingsMenu.panel.querySelector('#characters-preview-toggle-btn'),null,'production exposes no DEV-only preview control');
 assert.equal(first.contentApproved,false,'candidate visibility does not grant formal content approval');
 report.checks.push('Complete real main constructor/init/createUI executed in production compile; real Settings initial state synchronized.');
 // Keep the ordinary opening camera, rather than an isolated calibration view.
 report.camera={position:app.camera.position.toArray(),quaternion:app.camera.quaternion.toArray()};
 const frames=await advanceMain(app,{maxFrames:frozenDirectory?120:16000,until:a=>submittedInstances(a).instances>0});
 report.day={frames,snapshot:app.characters.snapshot(),render:submittedInstances(app)};
 assert.ok(report.day.render.instances>0,`Production main must submit actual characters without opt-in; got ${report.day.render.instances}. enabled=${app.characters.enabled}, canRunContent=${app.characters.manager.canRunContent}`);
 assert.equal(app.characters.manager.canRunContent,true);
 assert.equal(app.characters.snapshot().contentEnabled,true);
 assert.equal(app.characters.snapshot().rollout,'candidate-visible');
 assert.equal(app.characters.snapshot().acceptance.complete,false);
 assert.ok(report.day.render.rootAttachedToMainScene);
 assert.ok(report.day.render.meshes.every(m=>m.isInstancedMesh&&m.vertices>0&&m.indices>0));
 report.checks.push('Ordinary startup submits nonzero real character geometry, approval stays false, acceptance stays incomplete.');
 button.click();
 report.off={snapshot:app.characters.snapshot(),settingsPressed:button.getAttribute('aria-pressed'),render:submittedInstances(app)};
 assert.equal(report.off.render.instances,0);assert.equal(report.off.snapshot.enabled,false);assert.equal(report.off.settingsPressed,'false');
 await advanceMain(app,{maxFrames:20});assert.equal(submittedInstances(app).instances,0);
 button.click();
 const onFrames=await advanceMain(app,{maxFrames:16000,until:a=>submittedInstances(a).instances>0});
 report.on={frames:onFrames,snapshot:app.characters.snapshot(),settingsPressed:button.getAttribute('aria-pressed'),render:submittedInstances(app)};
 assert.ok(report.on.render.instances>0);assert.equal(report.on.settingsPressed,'true');assert.equal(report.on.snapshot.contentApproved,false);
 report.checks.push('Real Settings button ordinary off removes instances; ordinary on repopulates same main scene without preview.');
 const nightFrames=await advanceMain(app,{daylight:0,maxFrames:16000,until:(a,frame)=>frame>=35&&submittedInstances(a).instances>0});
 report.nightPreparationFrames=nightFrames;
 const visibleStates=[...app.characters.manager.states.values()].filter(s=>s.binding&&s.lod<3&&s.visibility*s.readiness>0).map(s=>({id:s.actor.id,schedule:s.actor.schedule}));
 report.night={snapshot:app.characters.snapshot(),render:submittedInstances(app),visibleStates};
 assert.ok(report.night.render.instances>0,'guards remain nonzero at night');
 assert.ok(visibleStates.length>0);assert.ok(visibleStates.every(s=>s.schedule==='guard-duty'),'ceremonial and daily characters fade out at night');
 assert.equal(report.night.snapshot.contentApproved,false);
 report.checks.push('Night keeps nonzero guard instances and hides daytime schedules.');
 if(fullWorld){
  const allReadyFrames=await advanceMain(app,{daylight:1,maxFrames:24000,until:a=>a.characters.snapshot().loaded===38});
  report.fullPreparation={frames:allReadyFrames,snapshot:app.characters.snapshot()};
  assert.equal(app.characters.snapshot().loaded,38,'all 38 real production bindings must load');
  report.spawnAfterReady={camera:app.camera.position.toArray(),snapshot:app.characters.snapshot(),render:submittedInstances(app)};
  assert.ok(report.spawnAfterReady.render.instances>0,'ordinary opening view has actual submitted characters');
  report.spawnGeometry=exportProductionView(app,path.join(geometryDirectory,`production-visibility-spawn-geometry${suffix}.json.gz`),{far:135});
  app.controls.setPosition(-12,1.7,-90);app.camera.lookAt(-12,1,-80);app.camera.updateMatrixWorld(true);
  await advanceMain(app,{maxFrames:35});
  report.taiheNear={camera:app.camera.position.toArray(),snapshot:app.characters.snapshot(),render:submittedInstances(app)};
  assert.ok(report.taiheNear.render.instances>0,'Taihe near-field camera submits real characters');
  assert.ok(report.taiheNear.snapshot.near>0,'near-field view uses LOD0 without moving actors');
  report.taiheGeometry=exportProductionView(app,path.join(geometryDirectory,`production-visibility-taihe-geometry${suffix}.json.gz`),{far:135});
  report.checks.push('Fresh full world binds all 38 registry actors at their unchanged placements; Taihe near-field camera has actual LOD0 instances.');
 }
});
