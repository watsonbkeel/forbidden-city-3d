import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const script = path.join(root,'scripts/package-production.mjs');
test('packager verifies source metadata before creating an output and preserves built provenance', t => {
  assert.ok(fs.existsSync(script),'guarded production packager exists');
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),'palace-package-'));
  t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
  const fixture=path.join(temp,'source');fs.mkdirSync(fixture);
  fs.mkdirSync(path.join(fixture,'src'));fs.writeFileSync(path.join(fixture,'src/app.js'),'v1');
  fs.writeFileSync(path.join(fixture,'release.json'),'{"release":"R52"}');
  fs.mkdirSync(path.join(fixture,'dist'));fs.writeFileSync(path.join(fixture,'dist/index.html'),'app');
  const invoke=output=>spawnSync(process.execPath,[script,output],{cwd:fixture,encoding:'utf8'});
  const output=path.join(temp,'package');
  assert.notEqual(invoke(output).status,0);assert.equal(fs.existsSync(output),false);
  return import('../scripts/build-identity.mjs').then(({createBuildInfo})=>{
    const built=createBuildInfo({root:fixture,base:'/',sourceCommit:'a'.repeat(40),sourceDirty:true});
    fs.writeFileSync(path.join(fixture,'dist/build-info.json'),JSON.stringify(built));
    fs.mkdirSync(path.join(fixture,'dist/assets'));
    fs.writeFileSync(path.join(fixture,'dist/assets/app.js'),JSON.stringify(built));
    fs.writeFileSync(path.join(fixture,'dist/index.html'),`<meta name="palace-build-id" content="${built.buildId}"><script type="module" src="/assets/app.js"></script>`);
    fs.mkdirSync(path.join(fixture,'release/r52'),{recursive:true});
    for(const name of ['start.mjs','README.txt'])fs.copyFileSync(path.join(root,'release/r52',name),path.join(fixture,'release/r52',name));
    fs.writeFileSync(path.join(fixture,'src/app.js'),'v2');
    const stale=invoke(output);assert.notEqual(stale.status,0);assert.match(stale.stderr,/Stale dist/);assert.equal(fs.existsSync(output),false);
    const legacy=spawnSync(process.execPath,[path.join(root,'scripts/r51-package-production.mjs'),output],{cwd:fixture,encoding:'utf8'});
    assert.notEqual(legacy.status,0);assert.match(legacy.stderr,/Stale dist/);assert.equal(fs.existsSync(output),false,'legacy entry point cannot bypass source verification');
    fs.writeFileSync(path.join(fixture,'src/app.js'),'v1');
    const accepted=invoke(output);assert.equal(accepted.status,0,accepted.stderr);
    const manifest=JSON.parse(fs.readFileSync(path.join(output,'SHA256SUMS.json')));
    assert.deepEqual(manifest.build,built);assert.equal(manifest.sourceCommit,built.sourceCommit);
    assert.ok(manifest.files.find(f=>f.path==='dist/build-info.json'));
    assert.notEqual(invoke(output).status,0,'existing rollback package is never overwritten');
  });
});
