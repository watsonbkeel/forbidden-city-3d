// 无浏览器单元门禁：批次恢复、卸载、屋面壳和阴影包围盒。
const assert = require('node:assert/strict');
(async () => {
  const T = await import('three');
  const { BatchedBuilder } = await import('../src/render/BatchedBuilder.js');
  const { buildSilhouette } = await import('../src/render/SilhouetteBuilder.js');
  const { ShadowSetup } = await import('../src/render/ShadowSetup.js');
  const scene = new T.Scene();
  const material = new T.MeshStandardMaterial({ name: 'roof_tile_material' });
  const a = new T.Mesh(new T.BoxGeometry(), material);
  const b = new T.Mesh(new T.BoxGeometry(), material);
  a.position.x = 10; b.position.x = -10; a.castShadow = true;
  scene.add(a, b);
  const builder = new BatchedBuilder(scene);
  builder.begin();
  assert.equal(builder.batches.length, 1);
  assert.equal(a.visible, false);
  builder.end();
  assert.equal(a.visible, true);
  assert.equal(builder.container.parent, null);
  b.removeFromParent(); builder.begin(); builder.end();
  assert.equal(builder.batches.length, 0);
  const shell = buildSilhouette(scene);
  assert.equal(shell.castShadow, false);
  assert.equal(shell.visible, false);
  assert.equal(shell.geometry.attributes.normal, undefined);
  shell.geometry.computeBoundingBox();
  assert.equal(shell.geometry.boundingBox.min.x, 9.5);
  const shadows = new ShadowSetup({}); shadows.quality = 'high';
  const camera = new T.PerspectiveCamera();
  scene.updateMatrixWorld(true);
  shadows.updateShadowLOD(camera, [a], 150);
  assert.equal(a.castShadow, true);
  camera.position.x = 500;
  shadows.updateShadowLOD(camera, [a], 150);
  assert.equal(a.castShadow, false);
  camera.position.x = 10;
  shadows.updateShadowLOD(camera, [a], 150);
  assert.equal(a.castShadow, true);
  builder.dispose(); shell.geometry.dispose(); shell.material.dispose();
  a.geometry.dispose(); b.geometry.dispose(); material.dispose();
  console.log('P1-R 单元门禁PASS：批次恢复/卸载、屋面轮廓/无投影、远近阴影切换');
})().catch(error => { console.error(error); process.exit(1); });
