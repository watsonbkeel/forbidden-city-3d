import * as THREE from 'three';
const PLAN='https://www.dpm.org.cn/Uploads/File/2021/11/23/u619c5a27422d3.pdf';
const REVISION='r157-four-own-plan-outward-rows-v1';
const near=(a,b)=>Number.isFinite(a)&&Math.abs(a-b)<1e-7;
const fit=(side,end,page,ys)=>Object.freeze({id:`INSTANCE-A-WUMEN-${side.toUpperCase()}-${end.toUpperCase()}-PAVILION`,side,end,printedPage:page,
  pixelYs:Object.freeze(ys),x:side==='east'?-47.7:47.7,z:end==='north'?-6:-56.4,localX:side==='east'?-5.5:5.5,
  zs:Object.freeze(ys.map(y=>5.5-(y-ys[0])*11/(ys.at(-1)-ys[0])))});
// Four separately observed source rows; NONE is generated by mirroring another.
// Approximate full-render pixel centres, 2304x3000, north-up. Image down=-Z.
// Keep existing11m depth/7.5m height/column radius, not a new metric survey.
export const WUMEN_OUTER_SIDE_FITS=Object.freeze([
  fit('east','north',152,[1159,1196,1257,1346,1407,1447]),
  fit('east','south',152,[2433,2477,2537,2626,2687,2724]),
  fit('west','north',153,[1162,1198,1259,1348,1409,1448]),
  fit('west','south',153,[2435,2479,2539,2628,2688,2726]),
]);
function prepare(body,f) {
  const columns=body?.children.filter(m=>m.geometry?.type==='CylinderGeometry'&&near(m.position.x,f.localX)).sort((a,b)=>b.position.z-a.position.z)??[];
  if(!body?.isGroup||!near(body.position.x,f.x)||!near(body.position.y,12.3)||!near(body.position.z,f.z)||!near(body.userData.topY,7.5)
    ||!body.quaternion.equals(new THREE.Quaternion())||!body.scale.equals(new THREE.Vector3(1,1,1))||columns.length!==2
    ||!columns.every((m,i)=>near(m.position.z,i===0?5.5:-5.5)&&near(m.position.y,3.3)&&m.geometry===columns[0].geometry&&m.material===columns[0].material
      &&m.quaternion.equals(new THREE.Quaternion())&&m.scale.equals(new THREE.Vector3(1,1,1)))
    ||!body.userData.colliders||!columns.every(m=>body.userData.colliders.some(b=>near((b.min.x+b.max.x)/2,m.position.x)&&near((b.min.z+b.max.z)/2,m.position.z)&&near(b.min.y,0)&&near(b.max.y,3))))
    throw Error(`R157 retained outward row mismatch: ${f.id}`);
  return {body,f,columns};
}
function install({body,f,columns}) {
  const added=f.zs.slice(1,-1).map(z=>{const m=columns[0].clone();m.position.z=z;return m;}),geometry=columns[0].geometry;
  geometry.computeBoundingBox();
  const proxies=added.map(m=>{const b=geometry.boundingBox.clone().translate(m.position);b.min.y=Math.max(0,b.min.y);b.max.y=Math.min(3,b.max.y);return b;});
  body.add(...added);body.userData.colliders.push(...proxies); // retain both corner meshes AND their proxies untouched
  body.userData.structure={...body.userData.structure,id:f.id,parentId:'FC-86C9330D65',
    outerSideFit:{revision:REVISION,side:f.side,source:PLAN,printedPage:f.printedPage,pixelYs:[...f.pixelYs],localX:f.localX,columnZs:[...f.zs],columnCount:6,
      basis:'FOUR_SEPARATE_APPROXIMATE_OWN_PAGE_REGISTRATIONS_IN_RETAINED_MODEL_NOT_SURVEY',
      scope:'OUTWARD_SIDE_ONLY_NOT_FULL_PERIMETER_OR_INWARD_CONNECTION_REVIEW',runtimeCollision:'UNCHANGED_EXISTING_BODY_AABB_AND_PLATFORM_NO_NEW_ACCESS'},wholeObjectAccepted:false};
}
/** One identified existing body, used also for finite independent composition tests. */
export function refineWumenPavilionOuterSideColumns(body,{instanceId}={}) {
  const f=WUMEN_OUTER_SIDE_FITS.find(f=>f.id===instanceId);if(!f)return false;
  if(body?.userData.structure?.outerSideFit?.revision===REVISION)return false;
  install(prepare(body,f));return true;
}
/** Original host only; validate ALL four bodies BEFORE any mesh is added. */
export function refineWumenOuterSideColumns(b,parent) {
  if(b.ox!==0||b.oz!==-419.6)return false;
  if(parent?.userData.r157WumenOuterSideColumns)return false;
  if(parent?.name!=='午门'||parent.position.lengthSq()||!parent.quaternion.equals(new THREE.Quaternion())||!parent.scale.equals(new THREE.Vector3(1,1,1)))throw Error('R157 original outward-row host mismatch');
  const prepared=WUMEN_OUTER_SIDE_FITS.map(f=>{const a=parent.children.filter(o=>o.isGroup&&near(o.position.x,f.x)&&near(o.position.y,12.3)&&near(o.position.z,f.z)&&near(o.userData.topY,7.5));if(a.length!==1)throw Error(`R157 unique outward pavilion missing: ${f.id}`);return prepare(a[0],f);});
  prepared.forEach(install);parent.userData.r157WumenOuterSideColumns=REVISION;return true;
}
